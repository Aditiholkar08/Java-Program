public class fourth4 {
    public static void main(String[] args) {
        int num = 0;
        for (int i = 1; i <= 3; i++) {
            num = 3;
            for (int j = 1; j <= 3; j++) {
                System.out.print(num + "      ");
                num--;
            }
            System.out.println();
        }
    }

}
