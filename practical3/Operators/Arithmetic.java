public class Arithmetic {
    public static void main(String[] args) {
        int num1 = 10;
        int num2 = 5;

        System.out.println("Addition of two number=" + (num1 + num2));
        System.out.println("Substraction   if two number=" + (num1 - num2));

        System.out.println("Multiplition of two number=" + num1 * num2);
        System.out.println("Divition of two number=" + num1 / num2);
    }

}