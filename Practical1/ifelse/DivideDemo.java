public class DivideDemo {
    public static void main(String[] args) {
        int x = 20;
        if (x % 2 == 0 && x % 5 == 0 && x % 10 == 0) {
            System.out.println(x + " is divide by 2,5,and 10");
        } else {
            System.out.println(x + " is not divide by 2,5,and 10");
        }
    }

}
